DECLARE
    staff_ids UUID[] := ARRAY[
        'c0000000-0000-0000-0000-000000000001'::UUID,
        'c0000000-0000-0000-0000-000000000002'::UUID,
        'c0000000-0000-0000-0000-000000000003'::UUID,
        'c0000000-0000-0000-0000-000000000004'::UUID
    ];
    sid UUID;
    days TEXT[] := ARRAY['MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'];
    d TEXT;
BEGIN
    FOREACH sid IN ARRAY staff_ids LOOP
        FOREACH d IN ARRAY days LOOP
            INSERT INTO staff_schedules (id, staff_id, day_of_week, is_working, start_time, end_time)
            VALUES (
                gen_random_uuid(),
                sid,
                d,
                d != 'SUNDAY',
                CASE WHEN d != 'SUNDAY' THEN '10:00:00'::TIME ELSE NULL END,
                CASE WHEN d != 'SUNDAY' THEN '20:00:00'::TIME ELSE NULL END
            ) ON CONFLICT (staff_id, day_of_week) DO NOTHING;
        END LOOP;
    END LOOP;
END $$;

